func init() {
	cmdmain.RegisterSubCmd("webrtc", func() cmdmain.SubCmd { return new(WebRTC) })
}

type WebRTCCodecParameters struct {
	MimeType    string
	ClockRate   uint32
	PayloadType uint8
}

var WebRTCExtraCodecs = []WebRTCCodecParameters{}

// webrtcSetupTimeout bounds waiting for signalling to complete and for the peer
// to open a data channel.
const webrtcSetupTimeout = 30 * time.Second

type WebRTC struct {
	localAddr        string
	remoteAddr       string
	localPort        string
	remotePort       string
	offer            bool
	bwe              string
	maxTargetRate    uint
	traceOutgoingRTP bool
	traceIncomingRTP bool
	datachannel      bool
	dcSourceFile     string
	dcStartDelay     uint
	dcChunks         bool
	pionCCFB         bool
	pionTWCC         bool
	pionReports      bool
	pionNACK         bool
	pionReadCCFB     bool
	sendVideoTrack   bool
	pacing           bool

	media mediaFlags
}

// Help implements cmdmain.SubCmd.
func (w *WebRTC) Help() string {
	return "Run webrtc peer"
}

func (w *WebRTC) Exec(cmd string, args []string) error {
	fs := flag.NewFlagSet("webrtc", flag.ExitOnError)
	fs.StringVar(&w.localAddr, "local", "127.0.0.1", "Local address of the HTTP signaling server the answerer listens on")
	fs.StringVar(&w.remoteAddr, "remote", "127.0.0.1", "Remote address of the HTTP signaling server the offerer connects to")
	fs.StringVar(&w.bwe, "bwe", "", "Set a bandwidth estimator by name, e.g. 'nada', 'gcc' or 'scream'")
	fs.UintVar(&w.maxTargetRate, "max-target-rate", 30_000_000, "Set the maximum target rate of the congestion controller in bits per second")
	fs.BoolVar(&w.traceOutgoingRTP, "trace-rtp-send", false, "Log outgoing RTP packets")
	fs.BoolVar(&w.traceIncomingRTP, "trace-rtp-recv", false, "Log incoming RTP packets")

	fs.StringVar(&w.localPort, "local-port", "8080", "Local port of the HTTP signaling server the answerer listens on")
	fs.StringVar(&w.remotePort, "remote-port", "8080", "Remote port of the HTTP signaling server the offerer connects to")

	fs.BoolVar(&w.offer, "offer", false, "Act as the offerer for WebRTC signaling")
	fs.BoolVar(&w.pionCCFB, "pion-ccfb", false, "Send RTCP CCFB packets generated by Pion")
	fs.BoolVar(&w.pionTWCC, "pion-twcc", false, "Send RTCP TWCC packets generated by Pion")
	fs.BoolVar(&w.pionReports, "pion-reports", false, "Send RTCP SR/RR packets generated by Pion")
	fs.BoolVar(&w.pionNACK, "pion-nack", false, "Send RTCP NACK packets generated by Pion")
	fs.BoolVar(&w.pionReadCCFB, "pion-read-ccfb", false, "Let Pion read incoming CCFB reports")
	fs.BoolVar(&w.sendVideoTrack, "send-track", false, "Send a media track to the peer")

	fs.BoolVar(&w.datachannel, "dc", false, "Send/Receive data with data channels")
	fs.StringVar(&w.dcSourceFile, "dc-source", "", "File to be sent. If empty, synthetic data will be sent.")
	fs.UintVar(&w.dcStartDelay, "dc-start-delay", 0, "Start delay in seconds before data channel source starts sending data.")
	fs.BoolVar(&w.dcChunks, "dc-chunks", false, "Send chunks on datachannel")

	fs.BoolVar(&w.pacing, "pacing", false, "Enable packet pacing")

	w.media.configureSender(fs)
	w.media.configureReceiver(fs)
	DefaultBweFlags.ConfigureFlags(fs)

	fs.Usage = func() {
		fmt.Fprintf(os.Stderr, `Run a WebRTC pipeline

Usage:
	%v webrtc [flags]
`, cmd)
		fs.PrintDefaults()
		fmt.Fprintln(os.Stderr)
	}
	if err := fs.Parse(args); err != nil {
		return err
	}

	runner := pipeline.NewRunner()
	defer func() {
		if closeErr := runner.Close(); closeErr != nil {
			slog.Error("failed to close media pipeline", "error", closeErr)
		}
	}()
	media, err := w.media.newPipeline(runner)
	if err != nil {
		return err
	}

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	stdnet, err := ecnnet.New(
		ecnnet.SetRecvBufferSize(10_000_000), // 10MB
		ecnnet.TrackECN(w.pionCCFB),
	)
	if err != nil {
		return err
	}
	// Declared up front because the OnTrack handler below sends RTCP through
	// the transport, and the handler only runs once the transport exists.
	var transport *webrtc.Transport

	localCandidates := signaling.NewCandidates()
	webrtcOptions := []webrtc.Option{
		webrtc.SetNet(stdnet),
		webrtc.OnICECandidate(func(c *pionwebrtc.ICECandidateInit) {
			localCandidates.Push((*signaling.ICECandidate)(c))
		}),
		webrtc.SetSRTPBufferLimit(10_000_000), // 10MB
		webrtc.RegisterDefaultCodecs(),
		// Pion does not know the FAKE codec, so it has to be registered to be
		// negotiable. Peers then agree on it like on any other codec, instead
		// of one peer sending fake media on a track the other believes to be
		// H264.
		webrtc.RegisterFakeCodec(),
		webrtc.OnTrack(func(receiver *webrtc.RTPReceiver) {
			receiverConfig, configErr := w.media.receiverConfig("rtp-stream-sink")
			if configErr != nil {
				panic(configErr)
			}
			// What arrives is what the peers negotiated, which is not
			// necessarily what -codec names: that flag picks what this peer
			// sends.
			receiverConfig.codec = receiver.Codec()
			receiverConfig.payloadType = int(receiver.PayloadType())
			g := pipeline.NewGraph()
			if streamErr := media.addReceiver(g, receiverConfig, receiveEndpoints{
				rtp:           receiver,
				rtcpEndpoints: rtcpEndpoints{send: transport.RTCPSender(), recv: receiver.RTCPReceiver()},
			}); streamErr != nil {
				panic(streamErr)
			}
			runner.Add(g)
		}),
	}

	// Registered before the Enable* options below, which only add their
	// feedback to the codecs registered so far.
	for _, c := range WebRTCExtraCodecs {
		webrtcOptions = append(webrtcOptions, webrtc.AddExtraCodecs(c.MimeType, c.ClockRate, c.PayloadType))
	}

	if w.traceIncomingRTP {
		webrtcOptions = append(webrtcOptions, webrtc.EnableRTPRecvTraceLogging())
	}
	if w.traceOutgoingRTP {
		webrtcOptions = append(webrtcOptions, webrtc.EnableRTPSendTraceLogging())
	}
	if w.pionCCFB {
		webrtcOptions = append(webrtcOptions, webrtc.EnableCCFB())
	}
	if w.pionTWCC {
		webrtcOptions = append(webrtcOptions, webrtc.EnableTWCC())
	}
	if w.pionNACK {
		webrtcOptions = append(webrtcOptions, webrtc.EnableNACK())
	}
	if w.pionReports {
		webrtcOptions = append(webrtcOptions, webrtc.EnableRTCPReports())
	}
	if w.pionReadCCFB {
		webrtcOptions = append(webrtcOptions, webrtc.EnableCCFBReceiver())
	}
	if w.pacing {
		if w.bwe == "scream" {
			return errors.New("-pacing cannot be combined with -bwe scream")
		}
		webrtcOptions = append(webrtcOptions, webrtc.EnablePacing())
	}
	if w.bwe != "" {
		bweOptions, err := makeWebRTCBWE(w.bwe, BWEConfig{
			InitTargetRate: initTargetRate,
			MinTargetRate:  minTargetRate,
			MaxTargetRate:  w.maxTargetRate,
		})
		if err != nil {
			return err
		}
		webrtcOptions = append(webrtcOptions, bweOptions...)
	}

	setupCtx, cancelSetupCtx := context.WithTimeout(context.Background(), webrtcSetupTimeout)
	defer cancelSetupCtx()
	connectedCtx, cancelConnectedCtx := context.WithCancel(setupCtx)
	defer cancelConnectedCtx()
	webrtcOptions = append(webrtcOptions, webrtc.OnConnected(func() {
		cancelConnectedCtx()
	}))

	transport, err = webrtc.NewTransport(webrtcOptions...)
	if err != nil {
		return err
	}
	defer func() {
		if closeErr := transport.Close(); closeErr != nil {
			slog.Error("failed to close WebRTC transport", "error", closeErr)
		}
	}()

	if w.offer && w.datachannel {
		var dcSender *webrtc.DCsender
		dcSender, err = transport.NewDataChannelSender("data")
		if err != nil {
			return err
		}
		var source dataSource
		source, err = createDataSource(w.dcSourceFile, w.dcStartDelay, mrtp.RateBounds{}, w.dcChunks)
		if err != nil {
			return err
		}
		dataGraph := pipeline.NewGraph()
		if err = dataGraph.Connect(source, dcSender); err != nil {
			return err
		}
		runner.Add(dataGraph)
	}

	if w.sendVideoTrack {
		var senderConfig senderConfig
		senderConfig, err = w.media.senderConfig("rtp-stream-source")
		if err != nil {
			return err
		}
		senderConfig.rateBounds = mrtp.RateBounds{
			Initial: initTargetRate,
			Min:     minTargetRate,
			Max:     w.maxTargetRate,
		}

		var track *webrtc.RTPSender
		track, err = transport.AddLocalTrackWithCodec(senderConfig.codec.MimeType())
		if err != nil {
			return err
		}

		// TODO(ME): Cannot enable SCReAM here because WebRTC rewrites the SSRCs
		// of outgoing packets. Thus, the sender cannot use the feedback,
		// because the receiver will mirror the SSRC set by Pion and not the one
		// seen by the ScreamTx implementation.
		// Another problem in the current ScreamRx implementation is that it
		// does not correctly set the CCFB type (count value of the RTCP
		// header). Pion expects the correct type, otherwise it can't forward
		// the packet to the correct SSRC (because it cannot read the media SSRC
		// from a raw RTCP packet. The ScreamTx sender on the other hand,
		// expects the type set to 0.
		mediaGraph := pipeline.NewGraph()
		runner.Add(mediaGraph)
		var mediaSender mrtp.TargetBitrateSetter
		mediaSender, err = media.addSender(mediaGraph, senderConfig, sendEndpoints{
			rtp:           track,
			rtcpEndpoints: rtcpEndpoints{send: transport.RTCPSender(), recv: track.RTCPReceiver()},
		})
		if err != nil {
			return err
		}

		// let the congestion controller steer the encoder
		transport.ControlBitrate(mediaSender)
	} else {
		if err = transport.AddRemoteVideoTrack(); err != nil {
			return err
		}
	}

	// Signaling starts once all tracks and data channels are added, so that
	// the first offer negotiates them.
	if w.offer {
		signaler := &signaling.Client{BaseURL: fmt.Sprintf("http://%v", net.JoinHostPort(w.remoteAddr, w.remotePort))}
		var id string
		id, err = offerTrickle(setupCtx, signaler, transport, localCandidates)
		if err != nil {
			return err
		}
		defer closeSession(signaler, id)
	} else {
		handler := signaling.NewHandler(&peerAcceptor{transport: transport, candidates: localCandidates})
		defer handler.Close()
		mux := nethttp.NewServeMux()
		handler.Register(mux)
		var s *http.Server
		s, err = http.NewServer(
			http.H1Address(net.JoinHostPort(w.localAddr, w.localPort)),
			http.ListenH2(false),
			http.ListenH3(false),
			http.RedirectH1ToH3(false),
			http.Handle(mux),
		)
		if err != nil {
			return err
		}
		go func() {
			if listenErr := s.ListenAndServe(); listenErr != nil {
				panic(listenErr)
			}
		}()
	}

	if !w.offer && w.datachannel {
		var dcReceiver *webrtc.DCreceiver
		dcReceiver, err = transport.NewDataChannelReceiver(setupCtx)
		if err != nil {
			return err
		}
		var dataSink *data.Sink
		dataSink, err = data.NewSink()
		if err != nil {
			return err
		}
		dataGraph := pipeline.NewGraph()
		if err = dataGraph.Connect(dcReceiver, dataSink); err != nil {
			return err
		}
		runner.Add(dataGraph)
	}

	<-connectedCtx.Done()
	if err := setupCtx.Err(); err != nil {
		return fmt.Errorf("peer connection not established within %v: %w", webrtcSetupTimeout, err)
	}
	// TODO(ME): Remove this sleep. Without it, we seem too be sending to early
	// and scream will build up a queue and consequently drop some packets from
	// the queue, which is likely to be the key frame. We then have to wait for
	// the next keyframe.
	time.Sleep(75 * time.Millisecond)
	return runner.Run(ctx)
}

// peerAcceptor answers the one trickle ICE session of the offering peer.
type peerAcceptor struct {
	transport  *webrtc.Transport
	candidates *signaling.Candidates

	lock     sync.Mutex
	accepted bool
}

// Accept implements signaling.Acceptor.
func (a *peerAcceptor) Accept(ctx context.Context, _ string, request signaling.Request) (signaling.Session, signaling.Response, error) {
	if request.Protocol != signaling.ProtocolWebRTC || request.WebRTC == nil {
		return nil, signaling.Response{}, fmt.Errorf("%w: expected a webrtc offer", signaling.ErrBadRequest)
	}
	if !request.WebRTC.Trickle {
		return nil, signaling.Response{}, fmt.Errorf("%w: offer must trickle ICE candidates", signaling.ErrBadRequest)
	}
	a.lock.Lock()
	defer a.lock.Unlock()
	if a.accepted {
		return nil, signaling.Response{}, fmt.Errorf("%w: peer connection is already negotiated", signaling.ErrConflict)
	}
	if err := a.transport.SetOffer(request.WebRTC.SDP); err != nil {
		return nil, signaling.Response{}, fmt.Errorf("%w: invalid webrtc offer: %w", signaling.ErrBadRequest, err)
	}
	answer, err := a.transport.CreateAnswer(ctx)
	if err != nil {
		return nil, signaling.Response{}, err
	}
	a.accepted = true
	return peerSession{a}, signaling.Response{WebRTC: &signaling.WebRTCAnswer{SDP: answer}}, nil
}

// peerSession is the signaling session of the offering peer. The peer
// connection outlives it and closes when the command exits.
type peerSession struct {
	acceptor *peerAcceptor
}

// Close implements signaling.Session.
func (peerSession) Close() error {
	return nil
}

// AddICECandidate implements signaling.TrickleSession.
func (s peerSession) AddICECandidate(candidate signaling.ICECandidate) error {
	return s.acceptor.transport.AddICECandidate(pionwebrtc.ICECandidateInit(candidate))
}

// LocalCandidates implements signaling.TrickleSession.
func (s peerSession) LocalCandidates() *signaling.Candidates {
	return s.acceptor.candidates
}
